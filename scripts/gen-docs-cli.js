#!/usr/bin/env node
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const {
	COMMANDS,
	COMMAND_TIERS,
	COMMAND_DEFINITIONS,
	TYPED_COMMANDS,
	commandSummary,
	commandUsageLine,
	knownSubcommands,
} = require("./lib/command-registry");

const ROOT_DIR = path.resolve(__dirname, "..");
const DOCS_DIR = path.join(ROOT_DIR, "apps", "docs");
const CLI_DOCS_DIR = path.join(DOCS_DIR, "docs", "reference", "cli");
const SIDEBAR_PATH = path.join(DOCS_DIR, "sidebars.ts");
const MANIFEST_PATH = path.join(DOCS_DIR, "docs-manifest.json");

function getPackageMetadata() {
	const pkgPath = path.join(ROOT_DIR, "package.json");
	const pkg = JSON.parse(fs.readFileSync(pkgPath, "utf8"));
	return {
		version: pkg.version || "1.6.0",
		nodeEngine: pkg.engines?.node || "^20.19.0 || ^22.12.0 || >=23",
		npmEngine: pkg.engines?.npm || ">=9.0.0",
	};
}

function escapeMarkdown(text) {
	if (!text) return "";
	return text.replace(/\|/g, "\\|");
}

function cleanSummary(raw) {
	if (!raw) return "";
	const firstLine = Array.isArray(raw) ? raw[0] : String(raw).split("\n")[0];
	return firstLine.replace(/["\\]/g, "").trim();
}

function generateCommandDoc(commandName, pkgMeta) {
	const def = COMMAND_DEFINITIONS[commandName] || {};
	const tier = COMMAND_TIERS[commandName] || "core";
	const isGoverned = TYPED_COMMANDS.has(commandName);
	const rawSummary = commandSummary(commandName) || "";
	const summary = cleanSummary(rawSummary);
	const usage = commandUsageLine(commandName) || `Usage: amber ${commandName} --target <repo>`;
	const subcommands = knownSubcommands(commandName);

	let rawHelp = def.help;
	let helpLines = [];
	if (Array.isArray(rawHelp)) {
		helpLines = rawHelp;
	} else if (typeof rawHelp === "string") {
		helpLines = rawHelp.split("\n");
	}

	// Extract examples and options if present
	const exampleLines = [];
	let inExamples = false;
	for (const line of helpLines) {
		if (line.trim().toLowerCase().startsWith("examples:")) {
			inExamples = true;
			continue;
		}
		if (inExamples) {
			if (line.trim().startsWith("amber ") || line.trim().startsWith("node ")) {
				exampleLines.push(line.trim());
			}
		}
	}

	const isReadOnly =
		tier === "expert" && ["status", "explain"].includes(commandName)
			? true
			: ["audit", "doctor", "status", "explain", "next", "route"].includes(commandName) ||
				summary.toLowerCase().includes("read-only") ||
				summary.toLowerCase().includes("inspect");

	const nature = isReadOnly ? "read-only" : "governed-write";

	const lines = [
		"---",
		`id: ${commandName}`,
		`title: "amber ${commandName}"`,
		`sidebar_label: "${commandName}"`,
		`description: "${summary.replace(/"/g, '\\"')}"`,
		"---",
		"",
		"import CommandBlock from '@site/src/components/CommandBlock';",
		"",
		"<!-- Generated by scripts/lib/command-registry.js — do not edit manually. Edit scripts/lib/command-registry.js instead. -->",
		"",
		`# amber ${commandName}`,
		"",
		'<div className="amber-generated-banner">',
		`  <strong>Reference generated from Amber Protocol v${pkgMeta.version}</strong><br />`,
		`  Tier: <code>${tier}</code> • Classification: <code>${isGoverned ? "Governed Command" : "Standard Command"}</code>`,
		"</div>",
		"",
		`## Summary`,
		"",
		summary,
		"",
		"## Usage",
		"",
		"```bash",
		usage.replace(/^Usage:\s*/, ""),
		"```",
		"",
		"## Execution Contract",
		"",
		`<CommandBlock`,
		`  context="Target Repository"`,
		`  nature="${nature}"`,
		`  command="amber ${commandName} --target path/to/repo"`,
		`  expectedOutput="Governed command execution signal"`,
		`/>`,
		"",
	];

	if (subcommands.length > 0) {
		lines.push("## Subcommands", "");
		lines.push("| Subcommand | Description |");
		lines.push("| --- | --- |");
		for (const sub of subcommands) {
			lines.push(`| <code>${sub}</code> | Subcommand action for <code>${commandName}</code> |`);
		}
		lines.push("");
	}

	if (helpLines.length > 0) {
		lines.push("## Command Details", "", "```text", helpLines.join("\n"), "```", "");
	}

	if (exampleLines.length > 0) {
		lines.push("## Examples", "");
		for (const eg of exampleLines) {
			lines.push("```bash", eg, "```", "");
		}
	}

	lines.push(
		"## Boundaries & Safety",
		"",
		"- **Target Repository Scoping**: All mutations and reads are confined to `--target <path>`.",
		"- **Fail-Closed Behavior**: Corrupt governance state or invalid schema parameters immediately halt execution with non-zero exit codes.",
		"- **No Dynamic Spawning**: Command executes locally within the current process; it does not spawn unmonitored background daemons.",
		"",
	);

	return lines.join("\n");
}

function generateCliIndex(pkgMeta) {
	const lines = [
		"---",
		"id: index",
		'title: "CLI Command Reference Overview"',
		'sidebar_label: "Overview"',
		'description: "Complete reference for all 54 Amber Protocol CLI commands generated from command registry."',
		"---",
		"",
		"<!-- Generated by scripts/lib/command-registry.js — do not edit manually. Edit scripts/lib/command-registry.js instead. -->",
		"",
		"# CLI Command Reference",
		"",
		'<div className="amber-generated-banner">',
		`  <strong>Reference generated from Amber Protocol v${pkgMeta.version}</strong><br />`,
		`  Authoritative command vocabulary: 54 commands`,
		"</div>",
		"",
		"Amber Protocol exposes its governance capabilities through a single unified CLI entry point `amber` (or `node scripts/amber.js`).",
		"",
		"## Standard Command Invocations",
		"",
		"All commands accept `--target <repo>` to specify the path to the target repository being governed.",
		"",
		"```bash",
		"amber <command> --target <repo> [options]",
		"```",
		"",
		"## Commands by Tier",
		"",
	];

	const tiers = ["journey", "core", "expert", "deprecated"];
	const tierLabels = {
		journey: "🚀 Journey Entry Commands",
		core: "🛡️ Core Governance Commands",
		expert: "⚙️ Expert & Inspection Commands",
		deprecated: "⚠️ Deprecated Commands (v1 Compatibility)",
	};

	for (const t of tiers) {
		const cmds = COMMANDS.filter((c) => (COMMAND_TIERS[c] || "core") === t);
		if (cmds.length === 0) continue;
		lines.push(`### ${tierLabels[t]}`, "");
		lines.push("| Command | Summary | Governed | Link |");
		lines.push("| --- | --- | --- | --- |");
		for (const cmd of cmds) {
			const rawSummary = commandSummary(cmd) || "";
			const summary = escapeMarkdown(cleanSummary(rawSummary));
			const isGov = TYPED_COMMANDS.has(cmd) ? "Yes" : "No";
			lines.push(`| <code>${cmd}</code> | ${summary} | ${isGov} | [Docs](/reference/cli/${cmd}) |`);
		}
		lines.push("");
	}

	return lines.join("\n");
}

