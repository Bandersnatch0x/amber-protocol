function run(argv = process.argv.slice(2)) {
	const checkOnly = argv.includes("--check");
	const pkgMeta = getPackageMetadata();

	fs.mkdirSync(CLI_DOCS_DIR, { recursive: true });

	const generatedFiles = new Map();

	// 1. Generate CLI reference pages
	for (const cmd of COMMANDS) {
		const filePath = path.join(CLI_DOCS_DIR, `${cmd}.md`);
		const content = generateCommandDoc(cmd, pkgMeta);
		generatedFiles.set(filePath, content);
	}

	// 2. Generate CLI index
	const cliIndexPath = path.join(CLI_DOCS_DIR, "index.md");
	generatedFiles.set(cliIndexPath, generateCliIndex(pkgMeta));

	// 3. Generate sidebars.ts
	generatedFiles.set(SIDEBAR_PATH, generateSidebars());

	// 4. Generate manifest
	const manifestContent = JSON.stringify(generateCuratedManifest(pkgMeta), null, 2) + "\n";
	generatedFiles.set(MANIFEST_PATH, manifestContent);

	const changed = [];
	const stale = [];

	for (const [filePath, content] of generatedFiles.entries()) {
		const exists = fs.existsSync(filePath);
		const current = exists ? fs.readFileSync(filePath, "utf8") : null;

		// Normalize newlines for comparison
		const normCurrent = current ? current.replace(/\r\n/g, "\n") : null;
		const normContent = content.replace(/\r\n/g, "\n");

		if (normCurrent !== normContent) {
			if (checkOnly) {
				stale.push(path.relative(ROOT_DIR, filePath));
			} else {
				fs.mkdirSync(path.dirname(filePath), { recursive: true });
				fs.writeFileSync(filePath, normContent, "utf8");
				changed.push(path.relative(ROOT_DIR, filePath));
			}
		}
	}

	if (checkOnly) {
		if (stale.length > 0) {
			console.error(
				`ERROR: Generated CLI reference is stale (${stale.length} files differ). Run 'npm run docs:gen' to update.`,
			);
			for (const s of stale) {
				console.error(`  - ${s}`);
			}
			return 1;
		}
		console.log(
			`✅ Generated CLI reference is up to date (${generatedFiles.size} files verified).`,
		);
		return 0;
	}

	console.log(
		`✅ Generated ${generatedFiles.size} documentation files (${changed.length} written/updated).`,
	);
	return 0;
}

if (require.main === module) {
	process.exitCode = run();
}

