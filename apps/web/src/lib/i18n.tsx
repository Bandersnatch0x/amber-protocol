export type I18nKey = TranslationKey;

export const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, 'zh-CN': zh };

interface I18nContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, params?: TranslationParams) => string;
}

interface DetectLanguageInput {
  stored: string | null;
  browserLanguage: string | undefined;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function isSupportedLanguage(value: string | null | undefined): value is Language {
  return value === 'en' || value === 'zh-CN';
}

export function detectInitialLanguage({ stored, browserLanguage }: DetectLanguageInput): Language {
  if (isSupportedLanguage(stored)) return stored;
  if (browserLanguage?.toLowerCase().startsWith('zh')) return 'zh-CN';
  return 'en';
}

function readInitialLanguage(): Language {
  if (typeof window === 'undefined') return 'en';
  return detectInitialLanguage({
    stored: localStorage.getItem(LANGUAGE_STORAGE_KEY),
    browserLanguage: window.navigator.language,
  });
}

export function interpolate(template: string, params: TranslationParams = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => {
    const value = params[key];
    return value === undefined ? match : String(value);
  });
}

interface I18nProviderProps {
  children: ReactNode;
  initialLanguage?: Language;
}

export function I18nProvider({ children, initialLanguage }: I18nProviderProps) {
  const [language, setLanguageState] = useState<Language>(
    () => initialLanguage ?? readInitialLanguage(),
  );

  useEffect(() => {
    document.documentElement.lang = language;
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  }, [language]);

  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next);
  }, []);

  const t = useCallback(
    (key: TranslationKey, params?: TranslationParams) =>
      interpolate(dictionaries[language][key] ?? en[key], params),
    [language],
  );

  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error('useI18n must be used within an I18nProvider');
  }
  return ctx;
}
